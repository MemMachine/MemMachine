"""The Claude Code capture hook: what it reads off a transcript, and what it sends.

The hook is a standalone stdlib script rather than an importable package, so
it is loaded by path here.
"""

import importlib.util
import json
import sys
from pathlib import Path

import pytest

_HOOK_PATH = (
    Path(__file__).resolve().parents[4]
    / "integrations"
    / "claude-code"
    / "capture_transcript.py"
)


@pytest.fixture(scope="module")
def hook():
    spec = importlib.util.spec_from_file_location("capture_transcript", _HOOK_PATH)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules["capture_transcript"] = module
    spec.loader.exec_module(module)
    return module


def _record(**fields):
    return json.dumps({"timestamp": "2026-01-15T12:00:00Z", **fields})


def _transcript(tmp_path: Path, *records: str) -> Path:
    path = tmp_path / "transcript.jsonl"
    path.write_text("\n".join(records) + "\n", encoding="utf-8")
    return path


def test_typed_user_text_is_searchable(hook):
    assert hook.classify_user_text("why did the deploy fail?") == "user_message"


@pytest.mark.parametrize(
    "text",
    [
        "<system-reminder>\nremember to do the thing\n</system-reminder>",
        "<command-name>/model</command-name>",
        "Caveat: The messages below were generated by the user while running",
        "This session is being continued from a previous conversation",
    ],
)
def test_injected_text_is_not_searchable(hook, text):
    # Role cannot tell these from what the user typed, so they are classified
    # on their shape -- and they must stay out of the index.
    assert hook.classify_user_text(text) == "injected"
    assert "injected" not in hook.SEARCHABLE_SOURCES


def test_the_whole_turn_lands_on_one_timeline(hook, tmp_path):
    transcript = _transcript(
        tmp_path,
        _record(message={"role": "user", "content": "run the tests"}),
        _record(
            message={
                "role": "assistant",
                "content": [
                    {"type": "thinking", "thinking": "they want pytest"},
                    {"type": "text", "text": "Running them now."},
                    {
                        "type": "tool_use",
                        "name": "Bash",
                        "input": {"command": "pytest -q"},
                    },
                ],
            }
        ),
        _record(
            message={
                "role": "user",
                "content": [{"type": "tool_result", "content": [{"text": "3 passed"}]}],
            }
        ),
    )

    entries, mark = hook.entries_since(transcript, 0)

    assert mark == 3
    assert [entry["source"] for entry in entries] == [
        "user_message",
        "reasoning",
        "assistant_message",
        "tool_call",
        "tool_result",
    ]
    # Reachable by expanding around a message, never ranked against one.
    non_searchable = [
        entry for entry in entries if entry["source"] not in hook.SEARCHABLE_SOURCES
    ]
    assert {entry["source"] for entry in non_searchable} == {
        "reasoning",
        "tool_call",
        "tool_result",
    }
    assert "pytest -q" in next(
        entry["text"] for entry in entries if entry["source"] == "tool_call"
    )


def test_a_compaction_summary_is_stored_but_not_indexed(hook, tmp_path):
    transcript = _transcript(
        tmp_path,
        _record(
            isCompactSummary=True,
            message={"role": "user", "content": "Summary of the work so far"},
        ),
    )

    [entry] = hook.entries_since(transcript, 0)[0]

    # It stays on the timeline -- it is the one record of where the session
    # lost its context -- but indexing it would let a paraphrase outrank the
    # turns it paraphrases, which compaction leaves sitting right beside it.
    assert entry["source"] == "injected"
    assert entry["source"] not in hook.SEARCHABLE_SOURCES


def test_capture_resumes_from_the_mark(hook, tmp_path):
    transcript = _transcript(
        tmp_path,
        _record(message={"role": "user", "content": "first"}),
        _record(message={"role": "user", "content": "second"}),
    )

    _, mark = hook.entries_since(transcript, 0)
    hook.write_mark(tmp_path / "state", "sess-1", mark)

    transcript.write_text(
        transcript.read_text(encoding="utf-8")
        + _record(message={"role": "user", "content": "third"})
        + "\n",
        encoding="utf-8",
    )
    resumed, new_mark = hook.entries_since(
        transcript, hook.read_mark(tmp_path / "state", "sess-1")
    )

    assert [entry["text"] for entry in resumed] == ["third"]
    assert new_mark == 3


def test_an_unwritten_mark_re_sends_rather_than_skips(hook, tmp_path):
    # The mark is written only after the post succeeds, so a crash in between
    # repeats a turn. Losing it would be the worse failure.
    transcript = _transcript(
        tmp_path, _record(message={"role": "user", "content": "only"})
    )

    first, _ = hook.entries_since(transcript, hook.read_mark(tmp_path, "sess-1"))
    second, _ = hook.entries_since(transcript, hook.read_mark(tmp_path, "sess-1"))

    assert [entry["text"] for entry in first] == ["only"]
    assert [entry["text"] for entry in second] == ["only"]


def test_empty_messages_are_dropped(hook, tmp_path):
    transcript = _transcript(
        tmp_path,
        _record(message={"role": "user", "content": "   "}),
        _record(
            message={"role": "assistant", "content": [{"type": "text", "text": ""}]}
        ),
        _record(message={"role": "user", "content": "real"}),
    )

    entries, _ = hook.entries_since(transcript, 0)

    assert [entry["text"] for entry in entries] == ["real"]


def test_a_malformed_line_does_not_stop_the_capture(hook, tmp_path):
    path = tmp_path / "transcript.jsonl"
    path.write_text(
        "\n".join(
            [
                _record(message={"role": "user", "content": "before"}),
                "{not json",
                _record(message={"role": "user", "content": "after"}),
            ]
        )
        + "\n",
        encoding="utf-8",
    )

    entries, mark = hook.entries_since(path, 0)

    assert [entry["text"] for entry in entries] == ["before", "after"]
    assert mark == 3


def test_metadata_carries_what_recall_filters_on(hook):
    message = hook._message(
        {
            "source": "tool_call",
            "producer": "assistant",
            "text": "{}",
            "timestamp": "2026-01-15T12:00:00Z",
            "tool_name": "Bash",
        },
        "sess-1",
    )

    assert message["metadata"] == {
        "source": "tool_call",
        "session_id": "sess-1",
        "tool_name": "Bash",
    }
